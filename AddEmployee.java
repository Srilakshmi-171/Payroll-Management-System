    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String eid = emp.getText().trim();
        String nicno = nic.getText().trim();
        String first_name = fname.getText().trim();
        String last_name = lname.getText().trim();
        String date_of_birth = dob.getText().trim();
        String address = addr.getText().trim();
        String city = city1.getText().trim();
        String tel_home = thome.getText().trim();
        String tel_mobile = tmobile.getText().trim();
        String designation = deg.getText().trim();
        String department = dep.getText().trim();
        String date_of_joining = doj.getText().trim();
        String salary = sal.getText().trim();

        // Check required fields
        if (eid.isEmpty() || first_name.isEmpty()
                || last_name.isEmpty() || salary.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please fill all required fields."
            );
            return;
        }

        try {

            // Load database configuration
            Properties props = new Properties();

            try (InputStream input =
                    getClass().getResourceAsStream("db.properties")) {

                if (input == null) {
                    throw new java.io.FileNotFoundException(
                            "db.properties not found inside the package"
                    );
                }

                props.load(input);
            }

            // Load MySQL JDBC driver
            Class.forName("com.mysql.cj.jdbc.Driver");

            // Convert dates from dd/MM/yyyy to yyyy-MM-dd
            DateTimeFormatter formatter =
                    DateTimeFormatter.ofPattern("dd/MM/uuuu")
                            .withResolverStyle(ResolverStyle.STRICT);

            Date dobDate = null;
            Date dojDate = null;

            if (!date_of_birth.isEmpty()) {
                LocalDate localDob =
                        LocalDate.parse(date_of_birth, formatter);
                dobDate = Date.valueOf(localDob);
            }

            if (!date_of_joining.isEmpty()) {
                LocalDate localDoj =
                        LocalDate.parse(date_of_joining, formatter);
                dojDate = Date.valueOf(localDoj);
            }

            // Connect to MySQL
            try (Connection con = DriverManager.getConnection(
                    props.getProperty("db.url"),
                    props.getProperty("db.username"),
                    props.getProperty("db.password"))) {

                // Original table order: 13 columns
                String sql = "INSERT INTO employee VALUES "
                        + "(?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

                try (PreparedStatement pstmt = con.prepareStatement(sql)) {

                    pstmt.setString(1, eid);
                    pstmt.setString(2, nicno);
                    pstmt.setString(3, first_name);
                    pstmt.setString(4, last_name);

                    if (dobDate == null) {
                        pstmt.setNull(5, java.sql.Types.DATE);
                    } else {
                        pstmt.setDate(5, dobDate);
                    }

                    pstmt.setString(6, address);
                    pstmt.setString(7, city);
                    pstmt.setString(8, tel_home);
                    pstmt.setString(9, tel_mobile);
                    pstmt.setString(10, designation);
                    pstmt.setString(11, department);

                    if (dojDate == null) {
                        pstmt.setNull(12, java.sql.Types.DATE);
                    } else {
                        pstmt.setDate(12, dojDate);
                    }

                    pstmt.setString(13, salary);

                    int result = pstmt.executeUpdate();

                    if (result > 0) {
                        JOptionPane.showMessageDialog(
                                this,
                                "Employee details inserted successfully!"
                        );
                    }
                }
            }

        } catch (DateTimeParseException ex) {

            JOptionPane.showMessageDialog(
                    this,
                    "Invalid date! Enter dates in DD/MM/YYYY format."
            );

        } catch (ClassNotFoundException ex) {

            JOptionPane.showMessageDialog(
                    this,
                    "MySQL JDBC Driver not found. Check your MySQL connector."
            );

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(
                    this,
                    "Database Error: " + ex.getMessage()
            );

        } catch (Exception ex) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error: " + ex.getMessage()
            );
        }
    }//GEN-LAST:event_jButton1ActionPerformed

